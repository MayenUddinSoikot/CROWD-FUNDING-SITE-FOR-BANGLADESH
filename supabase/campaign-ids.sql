-- ============================================================
-- Shohay: public campaign ID numbers (SH-1001, SH-1002, …)
-- Paste into Supabase → SQL Editor → Run. Safe to run once.
-- Every campaign (existing and future) automatically gets a
-- short unique number so donors, campaigners and admins can
-- find it easily — shown publicly as e.g. SH-1042.
-- ============================================================

alter table public.campaigns
  add column if not exists campaign_no bigint
  generated by default as identity (start with 1001);

create unique index if not exists campaigns_campaign_no_idx
  on public.campaigns (campaign_no);
